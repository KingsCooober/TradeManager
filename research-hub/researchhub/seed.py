def seed_if_empty(force: bool = False) -> int:
    conn = db.connect()
    count = conn.execute("SELECT COUNT(*) AS c FROM reports").fetchone()["c"]
    if count and not force:
        return 0
    import json
    import re

    for sample in SAMPLES:
        content = sample["content"]
        cursor = conn.execute(
            "INSERT INTO reports (title, org, authors, industry, rating, target_price, "
            "stock_code, report_date, source_type, source_file, page_count, word_count, "
            "content, summary, key_points, key_data, risks, ai_model, ai_updated_at, "
            "tags, starred, read_status, created_at, updated_at) "
            "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (
                sample["title"], sample["org"], sample["authors"], sample["industry"],
                sample["rating"], sample["target_price"], sample["stock_code"],
                sample["report_date"], "text", "内置示例", 0,
                len(re.sub(r"\s+", "", content)), content, sample.get("summary", ""),
                json.dumps(sample.get("key_points", []), ensure_ascii=False),
                json.dumps(sample.get("key_data", []), ensure_ascii=False),
                sample.get("risks", ""), "示例数据", "",
                json.dumps(sample.get("tags", []), ensure_ascii=False),
                1 if sample.get("starred") else 0,
                sample.get("read_status", "unread"), db.now(), db.now(),
            ),
        )
        rid = cursor.lastrowid
        highlight = sample.get("highlight")
        if highlight and highlight[0] in content:
            conn.execute(
                "INSERT INTO highlights(report_id, text, color, note, anchor, created_at) "
                "VALUES (?,?,?,?,?,?)",
                (rid, highlight[0], "yellow", highlight[1], "", db.now()),
            )
    conn.commit()
    return len(SAMPLES)
